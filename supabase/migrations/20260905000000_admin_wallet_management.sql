-- Admin wallet management: the wallet ledger, and admin-facing search,
-- detail, transaction history, and manual adjustment functions.
--
-- The wallet and wallet_transactions tables are created here idempotently
-- because they may already exist from the server repo's own migration
-- (same Supabase project, two repos tracking migrations independently). This
-- file is safe to run whether or not that one has been applied.
--
-- As with admin_user_management.sql, every admin-facing function re-checks
-- authorisation itself (is_admin() or is_service_role()) rather than trusting
-- the caller, and reads/writes go through SECURITY DEFINER functions rather
-- than a new RLS policy — a wallet is not a profile, but the shape of "an
-- administrator needs to see every row" is the same problem already solved
-- there.

-- Ledger --------------------------------------------------------------------

create table if not exists public.wallets (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null unique references auth.users(id) on delete cascade,
  available_balance_cents bigint not null default 0 check (available_balance_cents >= 0),
  held_balance_cents bigint not null default 0 check (held_balance_cents >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.wallets is
  'One row per member. Total balance is available_balance_cents + held_balance_cents, computed on read rather than stored.';

create table if not exists public.wallet_transactions (
  id uuid primary key default gen_random_uuid(),
  wallet_id uuid not null references public.wallets(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  type text not null check (type in ('TOPUP','ESCROW_HOLD','ESCROW_RELEASE','WITHDRAWAL','REFUND')),
  amount_cents bigint not null,
  description text not null,
  status text not null check (status in ('PENDING','COMPLETED','FAILED','REFUNDED')),
  stripe_payment_intent_id text unique,
  stripe_event_id text unique,
  currency text not null default 'sgd',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.wallet_transactions is
  'Append-only ledger. amount_cents is signed: positive for credits, negative for debits. A correction is a new row, never an edit to an existing one.';

create index if not exists wallet_transactions_wallet_id_idx
  on public.wallet_transactions (wallet_id, created_at desc);

alter table public.wallets enable row level security;
alter table public.wallet_transactions enable row level security;

drop policy if exists "users read own wallet" on public.wallets;
create policy "users read own wallet"
  on public.wallets for select
  using (auth.uid() = user_id);

drop policy if exists "users read own transactions" on public.wallet_transactions;
create policy "users read own transactions"
  on public.wallet_transactions for select
  using (auth.uid() = user_id);

-- Two more transaction types, for a manual correction an administrator makes
-- directly against a wallet rather than one generated by top-up, escrow, or
-- withdrawal flows.
alter table public.wallet_transactions drop constraint if exists wallet_transactions_type_check;
alter table public.wallet_transactions add constraint wallet_transactions_type_check
  check (type in ('TOPUP','ESCROW_HOLD','ESCROW_RELEASE','WITHDRAWAL','REFUND','ADMIN_CREDIT','ADMIN_DEBIT'));

-- Wallet lookup ---------------------------------------------------------

/**
 * Searches wallets by the owner's display name, email address, account id,
 * or the wallet's own id.
 *
 * strpos rather than LIKE for the same reason as admin_search_users: '%' and
 * '_' typed into the search box should match literally, not act as wildcards.
 */
create function public.admin_search_wallets(
  search text default '',
  result_limit int default 25,
  result_offset int default 0
)
returns table (
  id uuid,
  user_id uuid,
  email text,
  display_name text,
  available_balance_cents bigint,
  held_balance_cents bigint,
  created_at timestamptz,
  total_count bigint
)
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  needle text := lower(trim(coalesce(search, '')));
begin
  if not (public.is_admin() or public.is_service_role()) then
    raise exception 'Not authorised' using errcode = '42501';
  end if;

  return query
    select
      w.id,
      w.user_id,
      u.email::text,
      p.display_name,
      w.available_balance_cents,
      w.held_balance_cents,
      w.created_at,
      count(*) over () as total_count
    from public.wallets w
    join auth.users u on u.id = w.user_id
    left join public.profiles p on p.id = u.id
    where
      needle = ''
      or strpos(lower(coalesce(u.email::text, '')), needle) > 0
      or strpos(lower(coalesce(p.display_name, '')), needle) > 0
      or strpos(lower(u.id::text), needle) > 0
      or strpos(lower(w.id::text), needle) > 0
    order by w.created_at desc
    limit least(greatest(result_limit, 1), 100)
    offset greatest(result_offset, 0);
end;
$$;

